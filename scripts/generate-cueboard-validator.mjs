import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { buildSync } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaText = readFileSync(resolve(root, "src/data/emotion-node-config.schema.json"), "utf8");
const schema = JSON.parse(schemaText);
const ajv = new Ajv2020({
  allErrors: true,
  strict: false,
  ownProperties: true,
  code: { source: true },
});
const validate = ajv.compile(schema);
const output = buildSync({
  stdin: { contents: standaloneCode(ajv, validate), resolveDir: root, sourcefile: "cueboard-validator.cjs", loader: "js" },
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  write: false,
  minify: false,
});
const fingerprint = createHash("sha256").update(schemaText).digest("hex");
const generated = `// @ts-nocheck — generated validator; typed by scene-shape-validator.d.ts.\n// Generated by scripts/generate-cueboard-validator.mjs.\n// Canonical schema SHA-256: ${fingerprint}\n${output.outputFiles[0].text}`;
const target = resolve(root, "src/lib/emotion/scene-shape-validator.js");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== generated) throw new Error("Cueboard validator is stale; regenerate from the canonical schema.");
} else writeFileSync(target, generated);
